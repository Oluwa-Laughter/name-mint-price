#!/usr/bin/env python3
"""Regenerate JSON and literal TypeScript ABIs for all dapp contracts/interfaces."""
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parents[1]
targets = {
    "src/ClassNFT.sol:ClassNFT": "classNFTAbi",
    "src/IPFSFileRegistry.sol:IPFSFileRegistry": "ipfsFileRegistryAbi",
    "src/ETHUSDPriceFeed.sol:ETHUSDPriceFeed": "ethUsdPriceFeedAbi",
    "src/interfaces/AggregatorV3Interface.sol:AggregatorV3Interface": "aggregatorV3Abi",
    "src/interfaces/IENSResolver.sol:IENSResolver": "ensResolverAbi",
}
# Inspect everything before overwriting exports, so a compilation failure leaves existing files alone.
exports = []
for target, constant in targets.items():
    result = subprocess.run(
        ["forge", "inspect", target, "abi", "--json"],
        cwd=root, check=True, capture_output=True, text=True,
    )
    exports.append((target.split(":")[1], constant, json.dumps(json.loads(result.stdout), indent=2)))

output = root / "abi"
output.mkdir(exist_ok=True)
# The frontend is a separate Git repository in this workspace. Keep its generated
# bindings self-contained so Vercel never needs access to ../contracts at build time.
frontend = root.parent / "frontend"
frontend_output = frontend / "src" / "lib" / "contracts" if (frontend / "package.json").exists() else None
if frontend_output:
    (frontend_output / "abi").mkdir(parents=True, exist_ok=True)
for name, constant, serialized in exports:
    (output / f"{name}.json").write_text(serialized + "\n")
    (output / f"{name}.ts").write_text(
        "// Generated by python3 scripts/export_abi.py. Do not edit manually.\n"
        f"export const {constant} = {serialized} as const;\n"
    )
    if frontend_output:
        (frontend_output / "abi" / f"{name}.json").write_text(serialized + "\n")
        (frontend_output / "abi" / f"{name}.ts").write_text((output / f"{name}.ts").read_text())
    print(f"Exported abi/{name}.json and abi/{name}.ts")

if frontend_output:
    deployment = json.loads((root / "deployments" / "sepolia.json").read_text())
    (frontend_output / "deployment.ts").write_text(
        "// Generated from contracts/deployments/sepolia.json. Do not edit manually.\n"
        "export const sepoliaDeployment = " + json.dumps(deployment, indent=2) + " as const;\n"
    )
    print("Synced all five ABIs and Sepolia deployment addresses to frontend/src/lib/contracts/")
